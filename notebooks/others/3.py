import numpy as np

# Create an array containing numbers from 10 to 50
x = np.arange(10, 51)

# Display the array
print("Array:", x)

# Number of elements
print("Number of elements:", x.size)

# Shape
print("Shape:", x.shape)

# Dimension
print("Dimension:", x.ndim)

# Data type
print("Data type:", x.dtype)